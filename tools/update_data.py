#!/usr/bin/env python3
"""Regenerates Data/NoDisenchant.lua and Data/OwnLoot.lua from the Forever client tables.

Source: wago.tools DB2 exports (ItemSparse + Item) of the newest `wowf` build, or the build given
as first argument (e.g. 1.60.1.70938). Prints the disenchant bands (ItemDisenchantLoot) as well,
so a changed band layout shows up when the data is refreshed.

    python3 tools/update_data.py [build]
"""

import csv
import io
import json
import sys
import urllib.request
from pathlib import Path

WAGO = "https://wago.tools"
ROOT = Path(__file__).resolve().parent.parent

FLAG0_NO_DISENCHANT = 0x8000          # ItemSparse.Flags_0
FLAG1_OWN_DISENCHANT_LOOT = 0x40000000  # ItemSparse.Flags_1
CLASS_WEAPON, CLASS_ARMOR = 2, 4


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": "DisenchantAdvisor data tool"})
    with urllib.request.urlopen(request, timeout=300) as response:
        return response.read().decode("utf-8")


def table(name, build):
    return list(csv.DictReader(io.StringIO(fetch(f"{WAGO}/db2/{name}/csv?build={build}"))))


def newest_build():
    builds = json.loads(fetch(f"{WAGO}/api/builds"))["wowf"]
    return builds[0]["version"]


def write_list(path, build, comment, name, ids):
    lines = [
        f"-- {comment}",
        f"-- Generated by tools/update_data.py from build {build}: do not edit by hand.",
        "",
        "local _, ns = ...",
        "",
        f"ns.{name} = {{}}",
        "",
        "for _, itemID in ipairs({",
    ]
    for i in range(0, len(ids), 12):
        lines.append("    " + ", ".join(str(x) for x in ids[i:i + 12]) + ",")
    lines += ["}) do", f"    ns.{name}[itemID] = true", "end", ""]
    path.write_text("\n".join(lines), encoding="utf-8")
    print(f"{path.relative_to(ROOT)}: {len(ids)} items")


def main():
    build = sys.argv[1] if len(sys.argv) > 1 else newest_build()
    print(f"build {build}")

    classes = {int(r["ID"]): int(r["ClassID"]) for r in table("Item", build)}
    sparse = table("ItemSparse", build)

    no_disenchant = sorted(
        int(r["ID"]) for r in sparse
        if int(r["Flags_0"]) & FLAG0_NO_DISENCHANT
        and classes.get(int(r["ID"])) in (CLASS_WEAPON, CLASS_ARMOR)
        and int(r["OverallQualityID"]) >= 2
    )
    own_loot = sorted(int(r["ID"]) for r in sparse if int(r["Flags_1"]) & FLAG1_OWN_DISENCHANT_LOOT)

    write_list(ROOT / "Data" / "NoDisenchant.lua", build,
               "Uncommon+ weapons and armor the game does not let you disenchant (ItemSparse Flags_0 0x8000).",
               "noDisenchant", no_disenchant)
    write_list(ROOT / "Data" / "OwnLoot.lua", build,
               "Items that disenchant into their own loot instead of the usual materials (ItemSparse Flags_1 0x40000000).",
               "ownLoot", own_loot)

    print("\nItemDisenchantLoot bands (class quality min-max skill), compare with Data/Bands.lua:")
    bands = table("ItemDisenchantLoot", build)
    for r in sorted(bands, key=lambda r: (int(r["Class"]), int(r["Quality"]), int(r["MinLevel"]))):
        print(f"  {r['Class']} {r['Quality']} {r['MinLevel']:>2}-{r['MaxLevel']:<2} skill {r['SkillRequired']}")


if __name__ == "__main__":
    main()
